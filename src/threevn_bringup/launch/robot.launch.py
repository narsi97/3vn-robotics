"""
Bring up a robot against a real execution target.

  make mock      target:=mock    no simulator, no hardware
  make robot     target:=esp32   the physical 3VN arm (Phase 5)

  make mock  PROFILE=so101_follower     the same, for the SO-101
  make robot PROFILE=so101_follower     target:=feetech, its servo bus

`transport` and `endpoint` say where a robot's hardware is for THIS run,
over what its profile says. They are how one profile reaches a serial
device on a Linux host, the same bus through a TCP port on a Mac, and
a simulated bus with nothing plugged in at all.

For Gazebo use `make sim`, which launches threevn_sim -- the simulator
hosts controller_manager in its own process, so it needs a different
top-level launch file. Everything BELOW that difference (controllers,
topics, actions) is identical, which is the whole point.

`profile` chooses the ROBOT and `target` chooses what executes it. They
are independent: the description comes from describe(), which knows
whether a profile is one of ours (generated by xacro) or somebody
else's (their URDF plus an overlay), so nothing here has to.

This package must never import or depend on anything Gazebo-specific.
"""
from launch import LaunchDescription
from launch.actions import (
    DeclareLaunchArgument,
    OpaqueFunction,
    RegisterEventHandler,
)
from launch.event_handlers import OnProcessExit
from launch.substitutions import LaunchConfiguration, PathJoinSubstitution
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue
from launch_ros.substitutions import FindPackageShare
from threevn_robot_description.describe import (
    controllers_file,
    describe,
    targets,
)

BRINGUP_PKG = 'threevn_bringup'


def _bring_up(context, *args, **kwargs):
    """Build the actions once `profile` and `target` are known."""
    profile = LaunchConfiguration('profile').perform(context)
    target = LaunchConfiguration('target').perform(context)

    # 'gz' is a real target of every profile and wrong HERE: it selects
    # a hardware plugin that only exists inside the simulator process,
    # and ros2_control_node would die on it with a pluginlib error that
    # does not mention launch files.
    allowed = [name for name in targets(profile) if name != 'gz']
    if target not in allowed:
        raise RuntimeError(
            f'target:={target} is not one of {allowed} for profile '
            f'{profile}. For Gazebo, launch threevn_sim instead.')

    # Which controllers file is a fact about the robot, so the profile
    # names it; where that file lives is a fact about this package.
    controllers = PathJoinSubstitution(
        [FindPackageShare(BRINGUP_PKG), 'config', controllers_file(profile)]
    )

    robot_description = ParameterValue(
        describe(profile, target=target, hardware={
            'transport': LaunchConfiguration('transport').perform(context),
            'endpoint': LaunchConfiguration('endpoint').perform(context),
        }),
        # The description is URDF XML. Without value_type=str, launch
        # tries to parse it as YAML and fails at startup.
        value_type=str,
    )

    control_node = Node(
        package='controller_manager',
        executable='ros2_control_node',
        parameters=[{'robot_description': robot_description}, controllers],
        output='screen',
    )

    robot_state_publisher = Node(
        package='robot_state_publisher',
        executable='robot_state_publisher',
        output='screen',
        parameters=[{'robot_description': robot_description}],
    )

    def spawner(name):
        return Node(
            package='controller_manager',
            executable='spawner',
            arguments=[name, '--controller-manager', '/controller_manager'],
            output='screen',
        )

    joint_state_broadcaster = spawner('joint_state_broadcaster')

    # Controllers are chained off the broadcaster rather than all started
    # at once: starting a trajectory controller before state is flowing
    # produces a confusing "no state interface" failure.
    return [
        control_node,
        robot_state_publisher,
        joint_state_broadcaster,
        RegisterEventHandler(
            OnProcessExit(
                target_action=joint_state_broadcaster,
                on_exit=[spawner('arm_controller'), spawner('gripper_controller')],
            )
        ),
    ]


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument(
            'profile', default_value='threevn_arm_v1',
            description='Robot profile in threevn_robot_description/config/',
        ),
        DeclareLaunchArgument(
            'target', default_value='mock',
            description=(
                "Hardware target: 'mock', or the robot's own hardware "
                "('esp32' for the 3VN arm, 'feetech' for the SO-101). "
                "'gz' is intentionally absent here -- use threevn_sim for "
                'Gazebo, which hosts controller_manager itself.'
            ),
        ),
        DeclareLaunchArgument(
            'transport', default_value='',
            description=(
                "Override the hardware transport: 'serial' or 'tcp'. "
                "Empty uses the profile's."
            ),
        ),
        DeclareLaunchArgument(
            'endpoint', default_value='',
            description=(
                'Override where the hardware is: a serial device, or '
                "host:port for tcp. Empty uses the profile's."
            ),
        ),
        OpaqueFunction(function=_bring_up),
    ])
